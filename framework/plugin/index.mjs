// The framework's Vite plugin.
//
// It reads one root folder that holds `clients/`, `services/` and `components/`, and:
// - serves `virtual:framework/clients` and `virtual:framework/services`: the modules it finds
//   there, which the runtime turns into the injected trees;
// - resolves an import of a component folder (a folder with a `render` file and no `index`)
//   to a module it writes from the folder's files;
// - in a component's `style/` files, replaces the import of another component with that
//   component's escaped selector, so a skin can write `${Navigation} { … }`;
// - in a component's render, placeholder and error files, wraps every JSX `on…` handler in
//   `track(handler, site, key)`, so it is tracked with its placement;
// - resolves `@/…` to the root, for files inside the root;
// - writes one declaration per component folder, so TypeScript resolves folder imports
//   through `rootDirs`.
//
// The folder rules are shared with the TypeScript plugin (../shared/folders.cjs). Plain JavaScript, so a script can write
// the declarations without Vite (`write-types.mjs`).
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import MagicString from 'magic-string'
import { parseAst } from 'vite'
import folders from '../shared/folders.cjs'

const { CODE, posix, isDirectory, findLayer, listComponentFolders, declaredProps, componentPath, selector, listClients, listServices, listSkins, problems } = folders

const CLIENTS = 'virtual:framework/clients'
const SERVICES = 'virtual:framework/services'
const COMPONENT = '\0framework-component:'
const VIEW = 'framework-view:'
const HEADER = '// Generated by framework/plugin. Do not edit.'

/** @typedef {{ cwd: string, root: string, runtime: string, types: string }} Options */

/** @returns {Options} */
export function resolveOptions({ cwd = process.cwd(), root, runtime, types = '.framework-types' }) {
  return {
    cwd,
    root: path.resolve(cwd, root),
    runtime: path.resolve(cwd, runtime),
    types: path.resolve(cwd, types),
  }
}

const isComponentFolder = (options, dir) => folders.isComponentFolder(options.root, dir)

/**
 * Writes `<types>/<folder's path from cwd>/index.d.ts` for every component folder. With
 * `rootDirs` that merge the types folder with the sources, TypeScript sees each declaration
 * inside its component folder, so `import Navigation from './components/navigation'` resolves.
 * A folder whose `props.ts` exports a type named `Props` is declared with it, so what a parent
 * passes is checked; any other folder takes any props. The arguments injected into a
 * component's own files are typed by the TypeScript plugin (../typescript/).
 * Unchanged files are not rewritten, and each file is renamed into place whole.
 */
export function writeTypes(options) {
  const expected = new Map()
  for (const dir of listComponentFolders(options.root)) {
    const target = path.join(options.types, path.relative(options.cwd, dir), 'index.d.ts')
    const typed = declaredProps(dir)
    expected.set(
      target,
      [
        HEADER,
        "import type { ComponentType } from 'react';",
        ...(typed ? ["import type { Props } from './props';"] : []),
        '',
        `/** The component \`${componentPath(options.root, dir)}\`. */`,
        ...(typed
          ? ['declare const Component: ComponentType<Props & { className?: string }>;']
          : ['// eslint-disable-next-line @typescript-eslint/no-explicit-any', 'declare const Component: ComponentType<any>;']),
        'export default Component;',
        '',
      ].join('\n'),
    )
  }

  const existing = []
  const collect = (dir) => {
    if (!isDirectory(dir)) return
    for (const entry of readdirSync(dir)) {
      const file = path.join(dir, entry)
      if (isDirectory(file)) collect(file)
      else existing.push(file)
    }
  }
  collect(options.types)
  for (const file of existing) if (!expected.has(file)) rmSync(file, { force: true })
  for (const [file, source] of expected) {
    if (existsSync(file) && readFileSync(file, 'utf8') === source) continue
    mkdirSync(path.dirname(file), { recursive: true })
    const temporary = `${file}.${process.pid}.tmp`
    writeFileSync(temporary, source)
    renameSync(temporary, file)
  }
}

const HANDLER = /^on[A-Z]/
const TRACKED_LAYERS = new Set(['render', 'placeholder', 'error'])

const elementName = (name) => {
  if (name.type === 'JSXIdentifier') return name.name
  if (name.type === 'JSXMemberExpression') return `${elementName(name.object)}.${name.property.name}`
  if (name.type === 'JSXNamespacedName') return `${name.namespace.name}:${name.name.name}`
  return '?'
}

const walk = (node, visit) => {
  if (!node || typeof node !== 'object') return
  if (Array.isArray(node)) return node.forEach((child) => walk(child, visit))
  if (typeof node.type === 'string') visit(node)
  for (const key in node) if (key !== 'parent' && node[key] && typeof node[key] === 'object') walk(node[key], visit)
}

/**
 * Wraps every JSX `on…` attribute: `onClick={save}` becomes `onClick={__track(save, __site_0)}`,
 * with the site's placement hoisted as a frozen constant. `data-track="off"`
 * on an element leaves it alone, and the plugin removes the marker.
 */
function trackHandlers(code, id, componentPathValue, file, runtime) {
  if (!/\son[A-Z]/.test(code)) return null
  const ast = parseAst(code, { lang: 'tsx' }, id)
  const edits = new MagicString(code)
  const lineStarts = [0]
  for (let index = 0; index < code.length; index += 1) if (code[index] === '\n') lineStarts.push(index + 1)
  const locate = (offset) => {
    let low = 0
    let high = lineStarts.length - 1
    while (low < high) {
      const middle = (low + high + 1) >> 1
      if (lineStarts[middle] <= offset) low = middle
      else high = middle - 1
    }
    return { line: low + 1, column: offset - lineStarts[low] + 1 }
  }
  const sites = []
  walk(ast, (node) => {
    if (node.type !== 'JSXOpeningElement') return
    const element = elementName(node.name)
    const attributes = node.attributes.filter((attribute) => attribute.type === 'JSXAttribute')
    const optOut = attributes.find((attribute) => attribute.name.type === 'JSXIdentifier' && attribute.name.name === 'data-track' && attribute.value?.value === 'off')
    if (optOut) return void edits.remove(optOut.start, optOut.end)
    const keyAttribute = attributes.find((attribute) => attribute.name.type === 'JSXIdentifier' && attribute.name.name === 'key')
    const key =
      keyAttribute?.value?.type === 'JSXExpressionContainer'
        ? code.slice(keyAttribute.value.expression.start, keyAttribute.value.expression.end)
        : keyAttribute?.value
          ? code.slice(keyAttribute.value.start, keyAttribute.value.end)
          : undefined
    for (const attribute of attributes) {
      if (attribute.name.type !== 'JSXIdentifier' || !HANDLER.test(attribute.name.name)) continue
      if (attribute.value?.type !== 'JSXExpressionContainer' || attribute.value.expression.type === 'JSXEmptyExpression') continue
      const expression = attribute.value.expression
      const { line, column } = locate(attribute.start)
      const constant = `__site_${sites.length}`
      const site = {
        id: `${componentPathValue}#${element}.${attribute.name.name}@${line}:${column}`,
        path: componentPathValue,
        file,
        line,
        column,
        element,
        prop: attribute.name.name,
        handler: code.slice(expression.start, expression.end).slice(0, 80),
      }
      sites.push(`const ${constant} = /*#__PURE__*/ Object.freeze(${JSON.stringify(site)});`)
      edits.prependLeft(expression.start, '__track(')
      edits.appendRight(expression.end, `, ${constant}${key ? `, ${key}` : ''})`)
    }
  })
  if (!sites.length) return null
  edits.prepend(`import { track as __track } from ${runtime};\n${sites.join('\n')}\n`)
  return { code: edits.toString(), map: edits.generateMap({ hires: true, source: id }) }
}


/** @param {Options} options */
export default function framework(userOptions) {
  const options = resolveOptions(userOptions)
  const runtime = JSON.stringify(options.runtime)
  const isInside = (file) => file.startsWith(options.root + path.sep)
  const target = (source, importer) => {
    if (source.startsWith('@/')) return path.join(options.root, source.slice(2))
    if (source.startsWith('.')) return path.resolve(path.dirname(importer), source)
    return null
  }
  let isBuild = false

  return {
    name: 'framework',
    enforce: 'pre',

    configResolved(config) {
      isBuild = config.command === 'build'
    },

    buildStart() {
      writeTypes(options)
      for (const problem of problems(options.root)) this.warn(`${problem.file} ${problem.message}`)
    },

    configureServer(server) {
      // Adding or removing a file below the root can change a folder's layers, whether a folder
      // is a component, or the clients and services. Drop the generated modules and reload.
      let reload
      const refresh = (file) => {
        if (!isInside(file) || path.basename(file).startsWith('.')) return
        writeTypes(options)
        for (const problem of problems(options.root)) server.config.logger.warn(`[framework] ${problem.file} ${problem.message}`)
        for (const environment of Object.values(server.environments)) {
          const graph = environment.moduleGraph
          for (const [id, mod] of graph.idToModuleMap) {
            if (id.startsWith(COMPONENT) || id.startsWith(`\0${VIEW}`) || id === `\0${CLIENTS}` || id === `\0${SERVICES}`) {
              graph.invalidateModule(mod)
            }
          }
        }
        clearTimeout(reload)
        reload = setTimeout(() => {
          for (const environment of Object.values(server.environments)) environment.hot.send({ type: 'full-reload' })
        }, 50)
      }
      server.watcher.add(options.root)
      for (const event of ['add', 'unlink', 'addDir', 'unlinkDir']) server.watcher.on(event, refresh)
      // What a parent passes is declared from props.ts, so its changes rewrite the declarations.
      server.watcher.on('change', (file) => {
        if (isInside(file) && path.basename(file).replace(CODE, '') === 'props') writeTypes(options)
      })
    },

    async resolveId(source, importer) {
      if (source === CLIENTS || source === SERVICES || source.startsWith(VIEW)) return `\0${source}`
      if (source.startsWith(COMPONENT)) return source
      if (!importer || importer.startsWith('\0')) return null
      const file = importer.split('?')[0]
      // Inside the root, \`@/…\` and relative imports; outside it (an app's own shell), relative
      // imports, so a page can import a component folder.
      if (!isInside(file) && (source.startsWith('@/') || file.includes(`${path.sep}node_modules${path.sep}`))) return null
      const resolved = target(source, file)
      if (!resolved) return null
      if (isComponentFolder(options, resolved)) return COMPONENT + resolved
      if (source.startsWith('@/')) return this.resolve(resolved, importer, { skipSelf: true })
      return null
    },

    load(id) {
      if (id === `\0${CLIENTS}`) {
        const clients = listClients(options.root)
        return [
          ...clients.flatMap((client, index) => [
            `import * as client${index} from ${JSON.stringify(client.index)};`,
            ...(client.meta ? [`import * as meta${index} from ${JSON.stringify(client.meta)};`] : []),
          ]),
          `export default [${clients
            .map((client, index) => `{ folder: ${JSON.stringify(client.folder)}, module: client${index}${client.meta ? `, meta: meta${index}` : ''} }`)
            .join(', ')}];`,
        ].join('\n')
      }

      if (id === `\0${SERVICES}`) {
        const services = listServices(options.root).map((service) => ({ ...service, meta: findLayer(path.dirname(service.index), 'meta') }))
        return [
          ...services.flatMap((service, index) => [
            `import * as service${index} from ${JSON.stringify(service.index)};`,
            ...(service.meta ? [`import * as meta${index} from ${JSON.stringify(service.meta)};`] : []),
          ]),
          `export default [${services
            .map((service, index) => `{ segments: ${JSON.stringify(service.segments)}, module: service${index}${service.meta ? `, meta: meta${index}` : ''} }`)
            .join(', ')}];`,
        ].join('\n')
      }

      if (id.startsWith(COMPONENT)) {
        // The folder itself: the lazy view, its skins, and the eager placeholder and error
        // fallback.
        const dir = id.slice(COMPONENT.length)
        if (isBuild) this.addWatchFile(dir)
        const placeholder = findLayer(dir, 'placeholder')
        const error = findLayer(dir, 'error')
        const skins = listSkins(dir)
        return [
          `import { component } from ${runtime};`,
          ...(placeholder ? [`import placeholder from ${JSON.stringify(placeholder)};`] : []),
          ...(error ? [`import error from ${JSON.stringify(error)};`] : []),
          'export default component({',
          `  path: ${JSON.stringify(componentPath(options.root, dir))},`,
          `  view: () => import(${JSON.stringify(VIEW + dir)}),`,
          `  skins: { ${skins.map((skin) => `${JSON.stringify(skin.name)}: () => import(${JSON.stringify(skin.file)})`).join(', ')} },`,
          ...(placeholder ? ['  placeholder,'] : []),
          ...(error ? ['  error,'] : []),
          '});',
        ].join('\n')
      }

      if (id.startsWith(`\0${VIEW}`)) {
        // The view: the render and its layers, loaded together, lazily. With them, the component
        // folders the render imports: the runtime starts loading their views once this one has
        // loaded.
        const dir = id.slice(1 + VIEW.length)
        const render = findLayer(dir, 'render')
        if (isBuild) this.addWatchFile(render)
        const children = []
        for (const node of parseAst(readFileSync(render, 'utf8'), { lang: 'tsx' }, render).body) {
          if (node.type !== 'ImportDeclaration') continue
          const resolved = target(String(node.source.value), render)
          if (resolved && isComponentFolder(options, resolved) && !children.includes(resolved)) children.push(resolved)
        }
        const layer = (name) => {
          const file = findLayer(dir, name)
          return file ? `export * as ${name} from ${JSON.stringify(file)};` : `export const ${name} = undefined;`
        }
        return [
          ...children.map((child, index) => `import child${index} from ${JSON.stringify(COMPONENT + child)};`),
          `export { default as render } from ${JSON.stringify(render)};`,
          layer('props'),
          layer('async'),
          layer('state'),
          layer('form'),
          `export const children = [${children.map((_, index) => `child${index}`).join(', ')}];`,
        ].join('\n')
      }

      return null
    },

    transform(code, id) {
      const file = id.split('?')[0]
      if (!isInside(file) || !CODE.test(file)) return null
      const relative = posix(path.relative(options.root, file))

      // In a component's render, placeholder and error files, every `on…` handler is tracked.
      const layer = path.basename(file).replace(CODE, '')
      if (file.endsWith('.tsx') && TRACKED_LAYERS.has(layer) && isComponentFolder(options, path.dirname(file))) {
        return trackHandlers(code, id, componentPath(options.root, path.dirname(file)), relative, runtime)
      }

      // In a component's `style/` files, an imported component becomes its selector.
      // Read with the same parser as the renders: one way of reading source.
      if (!/(^|\/)style\//.test(relative)) return null
      const edits = new MagicString(code)
      for (const node of parseAst(code, { lang: 'ts' }, id).body) {
        if (node.type !== 'ImportDeclaration') continue
        const resolved = target(String(node.source.value), file)
        if (!resolved || !isComponentFolder(options, resolved)) continue
        const named = node.specifiers.filter((specifier) => specifier.type !== 'ImportDefaultSpecifier')
        if (named.length || !node.specifiers.length) {
          this.error(`${relative}: a skin imports a component only by its default name, as in \`import Navigation from '${node.source.value}'\`; a component has nothing else to import.`)
        }
        const name = node.specifiers[0].local.name
        edits.overwrite(node.start, node.end, `const ${name} = ${JSON.stringify(selector(componentPath(options.root, resolved)))};`)
      }
      return edits.hasChanged() ? { code: edits.toString(), map: edits.generateMap({ hires: true, source: id }) } : null
    },
  }
}
