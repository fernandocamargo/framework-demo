// The framework's Vite plugin.
//
// It reads one root folder that holds `clients/`, `services/` and `components/`, and:
// - serves `virtual:framework/clients`, `virtual:framework/services` and
//   `virtual:framework/messages`: the modules it finds
//   there, which the runtime turns into the injected trees;
// - resolves an import of a component folder (a folder with a `render` file and no `index`)
//   to a module it writes from the folder's files;
// - in a component's `style/` files, replaces the import of another component with that
//   component's escaped selector, so a skin can write `${Navigation} { … }`;
// - in a component's render, placeholder and error files, wraps every JSX `on…` handler in
//   `track(handler, site, key)`, so it is tracked with its placement; moves a function written
//   in the JSX that uses nothing of the render (a list's `{(item) => <Item … />}`) out of it, so
//   it is the same function at every render; and keeps one that reads the render
//   (`keep(fn, [values], site, key)`) for as long as the values it reads are the same;
// - in the same files, and in every other file that holds JSX (the app's shell, where `Root` is
//   given its folders), composes a component folder's boundaries around its element where it is
//   written: `<Row … />` becomes `bound(<Row … />)` (runtime/boundaries.ts), so a folder is one
//   component and its `Suspense` and error boundary sit above it;
// - writes, for a component folder with a `handlers.ts`, the hook that wires it: one `useCallback`
//   per export, whose dependencies are what the export reads, found in its source
//   (`handlersModule`); in that folder's render, an attribute given `handlers.<name>` stays as
//   written, since the hook's callbacks are tracked where they are made;
// - resolves `@/…` to the root, for files inside the root;
// - writes one declaration per component folder, so TypeScript resolves folder imports
//   through `rootDirs`.
//
// The folder rules are shared with the TypeScript plugin (../shared/folders.cjs). Plain JavaScript, so a script can write
// the declarations without Vite (`write-types.mjs`).

