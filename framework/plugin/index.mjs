/** @typedef {{ cwd: string, root: string, runtime: string, types: string }} Options */

/** @returns {Options} */
export function resolveOptions({ cwd = process.cwd(), root, runtime, types = '.framework-types' }) {
  return {
    cwd,
    root: path.resolve(cwd, root),
    runtime: path.resolve(cwd, runtime),
    types: path.resolve(cwd, types),
  };
}

const isComponentFolder = (options, dir) => folders.isComponentFolder(options.root, dir);

/**
 * Writes `<types>/<folder's path from cwd>/index.d.ts` for every component folder. With
 * `rootDirs` that merge the types folder with the sources, TypeScript sees each declaration
 * inside its component folder, so `import Navigation from './components/navigation'` resolves.
 * A folder whose `props.ts` exports a type named `Props` is declared with it, so what a parent
 * passes is checked; any other folder takes any props. The arguments injected into a
 * component's own files are typed by the TypeScript plugin (../typescript/).
 * Unchanged files are not rewritten, and each file is renamed into place whole.
 */
export function writeTypes(options) {
  const expected = new Map();
  for (const dir of listComponentFolders(options.root)) {
    const target = path.join(options.types, path.relative(options.cwd, dir), 'index.d.ts');
    const typed = declaredProps(dir);
    expected.set(
      target,
      [
        HEADER,
        "import type { ComponentType } from 'react';",
        ...(typed ? ["import type { Props } from './props';"] : []),
        '',
        `/** The component \`${componentPath(options.root, dir)}\`. */`,
        ...(typed
          ? ['declare const Component: ComponentType<Props & { className?: string }>;']
          : [
              '// eslint-disable-next-line @typescript-eslint/no-explicit-any',
              'declare const Component: ComponentType<any>;',
            ]),
        'export default Component;',
        '',
      ].join('\n'),
    );
  }

  const existing = [];
  const collect = (dir) => {
    if (!isDirectory(dir)) return;
    for (const entry of readdirSync(dir)) {
      const file = path.join(dir, entry);
      if (isDirectory(file)) collect(file);
      else existing.push(file);
    }
  };
  collect(options.types);
  for (const file of existing) if (!expected.has(file)) rmSync(file, { force: true });
  for (const [file, source] of expected) {
    if (existsSync(file) && readFileSync(file, 'utf8') === source) continue;
    mkdirSync(path.dirname(file), { recursive: true });
    const temporary = `${file}.${process.pid}.tmp`;
    writeFileSync(temporary, source);
    renameSync(temporary, file);
  }
}

const HANDLER = /^on[A-Z]/;
const TRACKED_LAYERS = new Set(['render', 'placeholder', 'error']);

const elementName = (name) => {
  if (name.type === 'JSXIdentifier') return name.name;
  if (name.type === 'JSXMemberExpression') return `${elementName(name.object)}.${name.property.name}`;
  if (name.type === 'JSXNamespacedName') return `${name.namespace.name}:${name.name.name}`;
  return '?';
};

const walk = (node, visit) => {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) return node.forEach((child) => walk(child, visit));
  if (typeof node.type === 'string') visit(node);
  for (const key in node) if (key !== 'parent' && node[key] && typeof node[key] === 'object') walk(node[key], visit);
};

const FUNCTIONS = new Set(['ArrowFunctionExpression', 'FunctionExpression', 'FunctionDeclaration']);
const children = (node, visit) => {
  for (const key in node) if (key !== 'parent' && node[key] && typeof node[key] === 'object') visit(node[key]);
};

/** The names a pattern binds: a parameter's, or a declaration's. */
const boundBy = (pattern, names) => {
  if (!pattern) return;
  if (pattern.type === 'Identifier') names.add(pattern.name);
  else if (pattern.type === 'ObjectPattern')
    for (const property of pattern.properties)
      boundBy(property.type === 'RestElement' ? property.argument : property.value, names);
  else if (pattern.type === 'ArrayPattern') for (const element of pattern.elements) boundBy(element, names);
  else if (pattern.type === 'AssignmentPattern') boundBy(pattern.left, names);
  else if (pattern.type === 'RestElement') boundBy(pattern.argument, names);
};

/** The names a function binds: its parameters and what its code declares, inside the functions it holds too when `deep`. */
const namesOf = (fn, deep) => {
  const names = new Set();
  const visit = (node) => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) return node.forEach(visit);
    if (FUNCTIONS.has(node.type)) {
      if (node.id) names.add(node.id.name);
      if (!deep) return;
      for (const parameter of node.params) boundBy(parameter, names);
    } else if (node.type === 'VariableDeclarator') boundBy(node.id, names);
    else if (node.type === 'ClassDeclaration' && node.id) names.add(node.id.name);
    else if (node.type === 'CatchClause') boundBy(node.param, names);
    children(node, visit);
  };
  for (const parameter of fn.params) boundBy(parameter, names);
  visit(fn.body);
  return names;
};

/** Every name some code refers to, the ones it binds itself included; `this` when it uses it. */
const referredBy = (code) => {
  const names = new Set();
  const visit = (node) => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) return node.forEach(visit);
    switch (node.type) {
      case 'BreakStatement':
      case 'ContinueStatement':
      case 'JSXClosingElement':
      case 'JSXIdentifier':
        return;
      case 'Identifier':
        return void names.add(node.name);
      case 'JSXAttribute':
        return visit(node.value);
      case 'JSXOpeningElement': {
        // `<Item>` and `<Menu.Item>` refer to a name; `<li>` does not.
        let name = node.name;
        while (name.type === 'JSXMemberExpression') name = name.object;
        if (name.type === 'JSXIdentifier' && (node.name.type === 'JSXMemberExpression' || /^[A-Z_$]/.test(name.name)))
          names.add(name.name);
        return visit(node.attributes);
      }
      case 'LabeledStatement':
        return visit(node.body);
      case 'MemberExpression':
        visit(node.object);
        if (node.computed) visit(node.property);
        return;
      case 'MethodDefinition':
      case 'Property':
      case 'PropertyDefinition':
        if (node.computed) visit(node.key);
        return visit(node.value);
      case 'ThisExpression':
        return void names.add('this');
    }
    children(node, visit);
  };
  visit(code);
  return names;
};

/**
 * What a function binds where its own code can see it: its parameters, and what its body declares
 * outside the functions it holds. Each with whether it stays the same through a render (a
 * parameter, a `const`, a function declaration), and where it is declared.
 */
const bindingsOf = (fn) => {
  const bindings = new Map();
  const bind = (pattern, binding) => {
    const names = new Set();
    boundBy(pattern, names);
    for (const name of names) bindings.set(name, binding);
  };
  for (const parameter of fn.params) bind(parameter, { at: -1, stable: true });
  const visit = (node) => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) return node.forEach(visit);
    if (FUNCTIONS.has(node.type)) return void (node.id && bindings.set(node.id.name, { at: -1, stable: true }));
    if (node.type === 'VariableDeclaration') {
      for (const declarator of node.declarations) {
        bind(declarator.id, { at: declarator.end, stable: node.kind === 'const' });
        visit(declarator.init);
      }
      return;
    }
    if (node.type === 'ClassDeclaration' && node.id) bindings.set(node.id.name, { at: node.end, stable: false });
    else if (node.type === 'CatchClause') bind(node.param, { at: -1, stable: false });
    children(node, visit);
  };
  visit(fn.body);
  return bindings;
};

/** The `key` an element is given, as written, or nothing. */
const keyOf = (opening, code) => {
  const attribute = opening.attributes.find(
    (each) => each.type === 'JSXAttribute' && each.name.type === 'JSXIdentifier' && each.name.name === 'key',
  );
  if (!attribute?.value) return undefined;
  const value = attribute.value.type === 'JSXExpressionContainer' ? attribute.value.expression : attribute.value;
  return code.slice(value.start, value.end);
};

/**
 * The functions written in the JSX of a render (a child, `{(item) => <Item … />}`, or an attribute
 * that is not a handler), each with the names of the render it reads (`deps`):
 * - one that reads none uses only its own parameters, what the module imports or declares, and
 *   globals. It is the same at every render, so it can live outside it;
 * - one that reads some, each a parameter or a `const` declared before it, is the same function as
 *   long as those are the same values (`keep`, track.ts).
 * Either way the element it is given to is equal to the one before (elements.ts), and React skips
 * it: a list is not rendered again because its parent was. One that holds a handler stays as
 * written: its handler is tracked where it is written. So does one that reads a `let`, a name
 * declared after it, `this` or `arguments`, or binds a name of the render again.
 */
function jsxFunctions(ast, code) {
  const found = [];
  const classify = (fn, around, key) => {
    if (fn.type !== 'ArrowFunctionExpression' || fn.async) return null;
    const source = code.slice(fn.start, fn.end);
    if (/\son[A-Z]/.test(source) || source.includes('data-track')) return null;
    const own = namesOf(fn, true);
    const referred = referredBy(fn);
    if (referred.has('this') || referred.has('arguments')) return null;
    const deps = [];
    for (const [name, binding] of around) {
      if (own.has(name)) return null;
      if (!referred.has(name)) continue;
      if (!binding.stable || binding.at > fn.start) return null;
      deps.push(name);
    }
    return { deps, fn, key };
  };
  const visit = (node, around, key) => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) return node.forEach((child) => visit(child, around, key));
    // A key belongs to the function that writes it: a function inside starts without one.
    if (FUNCTIONS.has(node.type))
      return children(node, (child) => visit(child, new Map([...(around ?? []), ...bindingsOf(node)]), undefined));
    if (node.type === 'JSXElement')
      return children(node, (child) => visit(child, around, keyOf(node.openingElement, code) ?? key));
    // Outside every function there is no render to keep it for.
    if (around && node.type === 'JSXExpressionContainer') {
      const function_ = classify(node.expression, around, key);
      if (function_) return void found.push(function_);
    }
    if (node.type === 'JSXAttribute' && node.name.type === 'JSXIdentifier' && HANDLER.test(node.name.name)) return;
    children(node, (child) => visit(child, around, key));
  };
  visit(ast, null, undefined);
  return found;
}

/**
 * Wraps every JSX `on…` attribute: `onClick={save}` becomes `onClick={__track(save, __site_0)}`,
 * with the site's placement hoisted as a frozen constant. `data-track="off"`
 * on an element leaves it alone, and the plugin removes the marker. It also moves the functions
 * that use nothing of the render out of it, and keeps the ones that read the render for as long as
 * what they read is the same (jsxFunctions).
 */
export function transformRender(code, id, componentPathValue, file, runtime) {
  if (!/\son[A-Z]/.test(code) && !code.includes('=>')) return null;
  const ast = parseAst(code, { lang: 'tsx' }, id);
  const edits = new MagicString(code);
  const lineStarts = [0];
  for (let index = 0; index < code.length; index += 1) if (code[index] === '\n') lineStarts.push(index + 1);
  const locate = (offset) => {
    let low = 0;
    let high = lineStarts.length - 1;
    while (low < high) {
      const middle = (low + high + 1) >> 1;
      if (lineStarts[middle] <= offset) low = middle;
      else high = middle - 1;
    }
    return { column: offset - lineStarts[low] + 1, line: low + 1 };
  };
  const moved = [];
  let kept = 0;
  for (const { deps, fn, key } of jsxFunctions(ast, code)) {
    if (!deps.length) {
      const name = `__constant_${moved.length}`;
      edits.overwrite(fn.start, fn.end, name);
      moved.push(`const ${name} = ${code.slice(fn.start, fn.end)};`);
      continue;
    }
    const { column, line } = locate(fn.start);
    edits.prependLeft(fn.start, '__keep(');
    edits.appendRight(
      fn.end,
      `, [${deps.join(', ')}], ${JSON.stringify(`${componentPathValue}@${line}:${column}`)}${key ? `, ${key}` : ''})`,
    );
    kept += 1;
  }
  const sites = [];
  walk(ast, (node) => {
    if (node.type !== 'JSXOpeningElement') return;
    const element = elementName(node.name);
    const attributes = node.attributes.filter((attribute) => attribute.type === 'JSXAttribute');
    const optOut = attributes.find(
      (attribute) =>
        attribute.name.type === 'JSXIdentifier' &&
        attribute.name.name === 'data-track' &&
        attribute.value?.value === 'off',
    );
    if (optOut) return void edits.remove(optOut.start, optOut.end);
    const keyAttribute = attributes.find(
      (attribute) => attribute.name.type === 'JSXIdentifier' && attribute.name.name === 'key',
    );
    const key =
      keyAttribute?.value?.type === 'JSXExpressionContainer'
        ? code.slice(keyAttribute.value.expression.start, keyAttribute.value.expression.end)
        : keyAttribute?.value
          ? code.slice(keyAttribute.value.start, keyAttribute.value.end)
          : undefined;
    for (const attribute of attributes) {
      if (attribute.name.type !== 'JSXIdentifier' || !HANDLER.test(attribute.name.name)) continue;
      if (
        attribute.value?.type !== 'JSXExpressionContainer' ||
        attribute.value.expression.type === 'JSXEmptyExpression'
      )
        continue;
      const expression = attribute.value.expression;
      const { column, line } = locate(attribute.start);
      const constant = `__site_${sites.length}`;
      const site = {
        column,
        element,
        file,
        handler: code.slice(expression.start, expression.end).slice(0, 80),
        id: `${componentPathValue}#${element}.${attribute.name.name}@${line}:${column}`,
        line,
        path: componentPathValue,
        prop: attribute.name.name,
      };
      sites.push(`const ${constant} = /*#__PURE__*/ Object.freeze(${JSON.stringify(site)});`);
      edits.prependLeft(expression.start, '__track(');
      edits.appendRight(expression.end, `, ${constant}${key ? `, ${key}` : ''})`);
    }
  });
  if (!sites.length && !moved.length && !kept) return null;
  const imported = [...(sites.length ? ['track as __track'] : []), ...(kept ? ['keep as __keep'] : [])];
  edits.prepend(
    `${imported.length ? `import { ${imported.join(', ')} } from ${runtime};\n` : ''}${sites.length ? `${sites.join('\n')}\n` : ''}${moved.length ? `${moved.join('\n')}\n` : ''}`,
  );
  return { code: edits.toString(), map: edits.generateMap({ hires: true, source: id }) };
}

/**
 * Where each key of a `shortcuts.ts` is declared, as the site of the interactions it runs: the
 * properties of the object its default export returns (`'mod+s': { label, send: 'save' }`), in
 * every branch of a condition.
 */
function shortcutSites(file, componentPathValue, root) {
  if (!file) return {};
  const code = readFileSync(file, 'utf8');
  const ast = parseAst(code, { lang: 'ts' }, file);
  const relative = posix(path.relative(root, file));
  const declaration = ast.body.find((node) => node.type === 'ExportDefaultDeclaration')?.declaration;
  const objects = (node) => {
    if (!node) return [];
    if (node.type === 'ObjectExpression') return [node];
    if (node.type === 'ConditionalExpression') return [...objects(node.consequent), ...objects(node.alternate)];
    if (node.type === 'TSAsExpression' || node.type === 'TSSatisfiesExpression') return objects(node.expression);
    if (
      node.type === 'ArrowFunctionExpression' ||
      node.type === 'FunctionExpression' ||
      node.type === 'FunctionDeclaration'
    ) {
      if (node.body.type !== 'BlockStatement') return objects(node.body);
      const returned = [];
      walk(node.body, (inner) => inner.type === 'ReturnStatement' && returned.push(...objects(inner.argument)));
      return returned;
    }
    return [];
  };
  const sites = {};
  for (const object of objects(declaration)) {
    for (const property of object.properties) {
      if (property.type !== 'Property' || property.computed) continue;
      const keys = property.key.type === 'Identifier' ? property.key.name : String(property.key.value);
      if (sites[keys]) continue;
      const before = code.slice(0, property.start);
      const line = before.split('\n').length;
      const column = property.start - before.lastIndexOf('\n');
      sites[keys] = {
        column,
        element: 'shortcuts',
        file: relative,
        handler: code.slice(property.value.start, property.value.end).replace(/\s+/g, ' ').slice(0, 80),
        id: `${componentPathValue}#shortcuts.${keys}@${line}:${column}`,
        line,
        path: componentPathValue,
        prop: keys,
      };
    }
  }
  return sites;
}

/** @param {Options} options */
export default function framework(userOptions) {
  const options = resolveOptions(userOptions);
  const runtime = JSON.stringify(options.runtime);
  const isInside = (file) => file.startsWith(options.root + path.sep);
  const target = (source, importer) => {
    if (source.startsWith('@/')) return path.join(options.root, source.slice(2));
    if (source.startsWith('.')) return path.resolve(path.dirname(importer), source);
    return null;
  };
  let isBuild = false;
  /** The sources each component folder's files read, as last written into its module. */
  const readsSeen = new Map();

  return {
    buildStart() {
      writeTypes(options);
      for (const problem of problems(options.root)) this.warn(`${problem.file} ${problem.message}`);
    },
    configResolved(config) {
      isBuild = config.command === 'build';
    },

    configureServer(server) {
      // Adding or removing a file below the root can change a folder's layers, whether a folder
      // is a component, or the clients and services. Drop the generated modules and reload.
      let reload;
      const refresh = (file) => {
        if (!isInside(file) || path.basename(file).startsWith('.')) return;
        writeTypes(options);
        for (const problem of problems(options.root))
          server.config.logger.warn(`[framework] ${problem.file} ${problem.message}`);
        for (const environment of Object.values(server.environments)) {
          const graph = environment.moduleGraph;
          for (const [id, mod] of graph.idToModuleMap) {
            if (
              id.startsWith(COMPONENT) ||
              id.startsWith(`\0${VIEW}`) ||
              id === `\0${CLIENTS}` ||
              id === `\0${SERVICES}` ||
              id === `\0${CHARTS}`
            ) {
              graph.invalidateModule(mod);
            }
          }
        }
        clearTimeout(reload);
        reload = setTimeout(() => {
          for (const environment of Object.values(server.environments)) environment.hot.send({ type: 'full-reload' });
        }, 50);
      };
      server.watcher.add(options.root);
      for (const event of ['add', 'unlink', 'addDir', 'unlinkDir']) server.watcher.on(event, refresh);
      // What a parent passes is declared from props.ts, so its changes rewrite the declarations.
      // What a component's files read decides what it subscribes to, so a change to it rewrites
      // the folder's module, and the page reloads.
      server.watcher.on('change', (file) => {
        if (!isInside(file)) return;
        if (path.basename(file).replace(CODE, '') === 'props') writeTypes(options);
        const dir = path.dirname(file);
        if (!readsSeen.has(dir) || !CODE.test(file)) return;
        if (JSON.stringify(readsOf(options.root, dir)) === readsSeen.get(dir)) return;
        for (const environment of Object.values(server.environments)) {
          const mod = environment.moduleGraph.getModuleById(COMPONENT + dir);
          if (mod) environment.moduleGraph.invalidateModule(mod);
        }
        refresh(file);
      });
    },

    enforce: 'pre',

    // The view's module holds what the plugin read of the folder's files (the folders its render
    // imports, where each key is declared), so an edit to one of them writes it again.
    hotUpdate({ file }) {
      const dir = path.dirname(file);
      if (!isInside(file) || !CODE.test(file) || !isComponentFolder(options, dir)) return;
      const view = this.environment.moduleGraph.getModuleById(`\0${VIEW}${dir}`);
      if (view) this.environment.moduleGraph.invalidateModule(view);
    },

    load(id) {
      if (id === `\0${CLIENTS}`) {
        const clients = listClients(options.root);
        return [
          ...clients.flatMap((client, index) => [
            `import * as client${index} from ${JSON.stringify(client.index)};`,
            ...(client.meta ? [`import * as meta${index} from ${JSON.stringify(client.meta)};`] : []),
          ]),
          `export default [${clients
            .map(
              (client, index) =>
                `{ folder: ${JSON.stringify(client.folder)}, module: client${index}${client.meta ? `, meta: meta${index}` : ''} }`,
            )
            .join(', ')}];`,
        ].join('\n');
      }

      if (id === `\0${SERVICES}`) {
        const services = listServices(options.root).map((service) => ({
          ...service,
          meta: findLayer(path.dirname(service.index), 'meta'),
        }));
        return [
          ...services.flatMap((service, index) => [
            `import * as service${index} from ${JSON.stringify(service.index)};`,
            ...(service.meta ? [`import * as meta${index} from ${JSON.stringify(service.meta)};`] : []),
          ]),
          `export default [${services
            .map(
              (service, index) =>
                `{ segments: ${JSON.stringify(service.segments)}, module: service${index}${service.meta ? `, meta: meta${index}` : ''} }`,
            )
            .join(', ')}];`,
        ].join('\n');
      }

      if (id === `\0${CHARTS}`) {
        // Every component folder with a state.ts: its path, the component, and the chart's file,
        // each loaded on demand, for the states gallery.
        const charted = listComponentFolders(options.root).flatMap((dir) => {
          const state = findLayer(dir, 'state');
          return state ? [{ dir, state }] : [];
        });
        return [
          `const charts = [${charted
            .map(
              ({ dir, state }) =>
                `{ path: ${JSON.stringify(componentPath(options.root, dir))}, component: () => import(${JSON.stringify(COMPONENT + dir)}), state: () => import(${JSON.stringify(state)}) }`,
            )
            .join(', ')}];`,
          'export default charts;',
          // Under the dev server, an edited chart is taken here, so the edit stops at its folder
          // (which takes its view) and the page is not reloaded; the gallery reads it when next shown.
          ...(isBuild
            ? []
            : [
                'if (import.meta.hot) {',
                ...charted.map(
                  ({ state }, index) =>
                    `  import.meta.hot.accept(${JSON.stringify(state)}, (chart) => chart && (charts[${index}].state = () => Promise.resolve(chart)));`,
                ),
                '}',
              ]),
        ].join('\n');
      }

      if (id.startsWith(COMPONENT)) {
        // The folder itself: the lazy view, its skins, the eager placeholder and error
        // fallback, its messages (eager, since the placeholder shows them too) with each
        // translation loaded on demand, and the sources its files read.
        const dir = id.slice(COMPONENT.length);
        if (isBuild) this.addWatchFile(dir);
        const placeholder = findLayer(dir, 'placeholder');
        const error = findLayer(dir, 'error');
        const i18n = findLayer(dir, 'i18n');
        const skins = listSkins(dir);
        const reads = readsOf(options.root, dir);
        readsSeen.set(dir, JSON.stringify(reads));
        return [
          `import { component } from ${runtime};`,
          ...(placeholder ? [`import placeholder from ${JSON.stringify(placeholder)};`] : []),
          ...(error ? [`import error from ${JSON.stringify(error)};`] : []),
          ...(i18n ? [`import * as i18n from ${JSON.stringify(i18n)};`] : []),
          'const folder = component({',
          `  path: ${JSON.stringify(componentPath(options.root, dir))},`,
          `  view: () => import(${JSON.stringify(VIEW + dir)}),`,
          `  skins: { ${skins.map((skin) => `${JSON.stringify(skin.name)}: () => import(${JSON.stringify(skin.file)})`).join(', ')} },`,
          ...(placeholder ? ['  placeholder,'] : []),
          ...(error ? ['  error,'] : []),
          ...(i18n
            ? [
                '  i18n,',
                `  translations: { ${listTranslations(dir)
                  .map(({ file, locale }) => `${JSON.stringify(locale)}: () => import(${JSON.stringify(file)})`)
                  .join(', ')} },`,
              ]
            : []),
          `  reads: ${JSON.stringify({
            // Every name acl.ts destructures: a rule that reads only `user` and `acl` is the folder's.
            acl: reads.names.acl ?? [],
            async: reads.byLayer.async ?? [],
            // What the chart's declaration destructures: it is declared again when those change.
            chart: reads.names.chart ?? [],
            state: reads.byLayer.state ?? [],
            view: [...new Set(['props', 'render', 'shortcuts'].flatMap((layer) => reads.byLayer[layer] ?? []))],
          })},`,
          '});',
          'export default folder;',
          // Under the dev server, the folder takes an edit to its view's files, or to a skin, where
          // it is: the runtime shows it in every instance on screen, which keeps its state. Authors
          // write `export default (props) => …`, which React's Fast Refresh does not take for a
          // component (and a render is not one: it is called as a function), so without this an
          // edit went up to the page and reloaded it.
          ...(isBuild
            ? []
            : [
                'if (import.meta.hot) {',
                `  import.meta.hot.accept(${JSON.stringify(VIEW + dir)}, (view) => view && folder.replace?.(view));`,
                ...skins.map(
                  (skin) =>
                    `  import.meta.hot.accept(${JSON.stringify(skin.file)}, (sheet) => sheet && folder.restyle?.(${JSON.stringify(skin.name)}, sheet));`,
                ),
                '}',
              ]),
        ].join('\n');
      }

      if (id.startsWith(`\0${VIEW}`)) {
        // The view: the render and its layers, loaded together, lazily. With them, the component
        // folders the render imports: the runtime starts loading their views once this one has
        // loaded.
        const dir = id.slice(1 + VIEW.length);
        const render = findLayer(dir, 'render');
        if (isBuild) this.addWatchFile(render);
        const found = new Set();
        for (const node of parseAst(readFileSync(render, 'utf8'), { lang: 'tsx' }, render).body) {
          if (node.type !== 'ImportDeclaration') continue;
          const resolved = target(String(node.source.value), render);
          if (resolved && isComponentFolder(options, resolved)) found.add(resolved);
        }
        const children = [...found];
        const layer = (name) => {
          const file = findLayer(dir, name);
          return file ? `export * as ${name} from ${JSON.stringify(file)};` : `export const ${name} = undefined;`;
        };
        return [
          ...children.map((child, index) => `import child${index} from ${JSON.stringify(COMPONENT + child)};`),
          `export { default as render } from ${JSON.stringify(render)};`,
          layer('props'),
          layer('async'),
          layer('state'),
          layer('form'),
          layer('acl'),
          layer('shortcuts'),
          `export const shortcutSites = ${JSON.stringify(shortcutSites(findLayer(dir, 'shortcuts'), componentPath(options.root, dir), options.root))};`,
          `export const children = [${children.map((_, index) => `child${index}`).join(', ')}];`,
        ].join('\n');
      }

      return null;
    },

    name: 'framework',

    async resolveId(source, importer) {
      if (source === CLIENTS || source === SERVICES || source === CHARTS || source.startsWith(VIEW))
        return `\0${source}`;
      if (source.startsWith(COMPONENT)) return source;
      if (!importer || importer.startsWith('\0')) return null;
      const file = importer.split('?')[0];
      // Inside the root, \`@/…\` and relative imports; outside it (an app's own shell), relative
      // imports, so a page can import a component folder.
      if (!isInside(file) && (source.startsWith('@/') || file.includes(`${path.sep}node_modules${path.sep}`)))
        return null;
      const resolved = target(source, file);
      if (!resolved) return null;
      if (isComponentFolder(options, resolved)) return COMPONENT + resolved;
      if (source.startsWith('@/')) return this.resolve(resolved, importer, { skipSelf: true });
      return null;
    },

    transform(code, id) {
      const file = id.split('?')[0];
      if (!isInside(file) || !CODE.test(file)) return null;
      const relative = posix(path.relative(options.root, file));

      // In a component's render, placeholder and error files, every `on…` handler is tracked, and
      // the functions that use nothing of the render are moved out of it.
      const layer = path.basename(file).replace(CODE, '');
      if (file.endsWith('.tsx') && TRACKED_LAYERS.has(layer) && isComponentFolder(options, path.dirname(file))) {
        return transformRender(code, id, componentPath(options.root, path.dirname(file)), relative, runtime);
      }

      // In a component's `style/` files, an imported component becomes its selector.
      // Read with the same parser as the renders: one way of reading source.
      if (!/(^|\/)style\//.test(relative)) return null;
      const edits = new MagicString(code);
      for (const node of parseAst(code, { lang: 'ts' }, id).body) {
        if (node.type !== 'ImportDeclaration') continue;
        const resolved = target(String(node.source.value), file);
        if (!resolved || !isComponentFolder(options, resolved)) continue;
        const named = node.specifiers.filter((specifier) => specifier.type !== 'ImportDefaultSpecifier');
        if (named.length || !node.specifiers.length) {
          this.error(
            `${relative}: a skin imports a component only by its default name, as in \`import Navigation from '${node.source.value}'\`; a component has nothing else to import.`,
          );
        }
        const name = node.specifiers[0].local.name;
        edits.overwrite(
          node.start,
          node.end,
          `const ${name} = ${JSON.stringify(selector(componentPath(options.root, resolved)))};`,
        );
      }
      return edits.hasChanged()
        ? { code: edits.toString(), map: edits.generateMap({ hires: true, source: id }) }
        : null;
    },
  };
}
