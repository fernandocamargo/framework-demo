// Every component folder in Storybook, with no story written by hand.
//
// `writeStories` writes one story file per component folder into a git-ignored folder
// (`framework-stories/<path>.stories.tsx`), as the plugin writes the folders' declarations into
// `.framework-types/`. Each file holds:
// - the folder's files (its layer files, its helpers and tests, its skins and translations), each
//   with its source, and what the framework knows of them: what each file is given and which
//   sources it follows (the plugin's `readsOf`), and the states of its chart;
// - a story for the component as it runs (a chart from its first state, with that state's example),
//   or one per example its `props.ts` exports (what a parent passes, the address it needs), and one
//   per state of its chart, held in that state (`Pinned`, with `state.ts`'s example for it), as the
//   states gallery shows them.
// Storybook needs each story as a named export, so the states are read from `state.ts`'s code: the
// object its default export returns, its nested `states`, and the states a spread may add.
// `storiesPlugin` writes them again when a folder or a file appears or goes, or a `state.ts` or a
// `props.ts` changes.
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseAst } from 'vite'
import folders from '../shared/folders.cjs'

const { CODE, posix, isDirectory, findLayer, listComponentFolders, componentPath, listSkins, listTranslations, readsOf } = folders

const HEADER = '// Generated by framework/storybook. Do not edit.'
const LAYERS = ['render', 'props', 'async', 'state', 'form', 'acl', 'i18n', 'shortcuts', 'placeholder', 'error']
const RESERVED = new Set(['default', 'delete', 'new', 'class', 'function', 'return', 'switch', 'case', 'var', 'let', 'const', 'import', 'export', 'in', 'do', 'if', 'for', 'while', 'with', 'this', 'void', 'typeof', 'try', 'catch', 'finally', 'throw', 'super', 'yield', 'await', 'enum', 'null', 'true', 'false'])

/** @typedef {{ cwd: string, root: string, out: string, docs: string, skip: string[] }} Options */

/** @returns {Options} */
// Not a folder whose name starts with a dot: Storybook's watcher matches the files it sees against
// the stories' glob, which skips such folders, so it would not see a story file change.
/** `skip`: component paths with no story file, such as a page that only works inside the app's own shell. */
export function resolveStoriesOptions({ cwd = process.cwd(), root, out = 'framework-stories', skip = [] }) {
  return { cwd, root: path.resolve(cwd, root), out: path.resolve(cwd, out), docs: path.resolve(import.meta.dirname, 'docs.tsx'), skip }
}

/** An expression with its TypeScript wrappers taken off: `x as T`, `x satisfies T`, `(x)`. */
const bare = (node) => {
  let current = node
  while (current && ['TSAsExpression', 'TSSatisfiesExpression', 'ParenthesizedExpression', 'TSNonNullExpression'].includes(current.type)) current = current.expression
  return current
}

const keyName = (property) => (property.key.type === 'Identifier' ? property.key.name : typeof property.key.value === 'string' ? property.key.value : null)

/** The object literals an expression may evaluate to: itself, either side of `a && {…}`, either branch of `c ? {…} : {…}`. */
const objectsOf = (node) => {
  const value = bare(node)
  if (!value) return []
  if (value.type === 'ObjectExpression') return [value]
  if (value.type === 'LogicalExpression') return [...objectsOf(value.left), ...objectsOf(value.right)]
  if (value.type === 'ConditionalExpression') return [...objectsOf(value.consequent), ...objectsOf(value.alternate)]
  return []
}

/** The properties of an object literal, the ones a spread of a literal may add included. */
const propertiesOf = (object) =>
  object.properties.flatMap((property) => (property.type === 'SpreadElement' ? objectsOf(property.argument).flatMap(propertiesOf) : property.type === 'Property' ? [property] : []))

const parse = (file) => parseAst(readFileSync(file, 'utf8'), { lang: /\.tsx$/.test(file) ? 'tsx' : 'ts' }, file)

/** The object a module's default export returns: `export default ({ … }) => ({ … })`. */
function defaultObject(file) {
  const ast = parse(file)
  const declaration = ast.body.find((node) => node.type === 'ExportDefaultDeclaration')?.declaration
  const fn = bare(declaration)
  if (!fn) return null
  if (fn.type === 'ObjectExpression') return fn
  if (fn.type !== 'ArrowFunctionExpression' && fn.type !== 'FunctionExpression') return null
  if (fn.body.type !== 'BlockStatement') return objectsOf(fn.body)[0] ?? null
  const returned = fn.body.body.find((statement) => statement.type === 'ReturnStatement')
  return returned ? (objectsOf(returned.argument)[0] ?? null) : null
}

/** The states of a chart, as `state.ts` declares them: each with its dotted path and its `description`. */
export function chartStates(file) {
  const states = []
  const walk = (object, prefix) => {
    for (const property of propertiesOf(object)) {
      const name = keyName(property)
      if (!name) continue
      const at = prefix ? `${prefix}.${name}` : name
      const node = objectsOf(property.value)[0]
      const description = node && propertiesOf(node).find((each) => keyName(each) === 'description')
      states.push({ path: at, description: description && bare(description.value).type === 'Literal' ? bare(description.value).value : undefined })
      const nested = node && propertiesOf(node).find((each) => keyName(each) === 'states')
      const children = nested && objectsOf(nested.value)[0]
      if (children) walk(children, at)
    }
  }
  const root = defaultObject(file)
  if (root) walk(root, '')
  return states
}

/** A module's `export const examples = …`, if it has one. */
function examplesOf(file) {
  if (!file) return undefined
  for (const node of parse(file).body) {
    if (node.type !== 'ExportNamedDeclaration' || node.declaration?.type !== 'VariableDeclaration') continue
    for (const declarator of node.declaration.declarations) {
      if (declarator.id.type === 'Identifier' && declarator.id.name === 'examples') return declarator
    }
  }
  return undefined
}

/** The names of a module's `export const examples = { … }`, in order. */
export function exampleNames(file) {
  const declarator = examplesOf(file)
  const object = declarator && objectsOf(declarator.init)[0]
  return object ? propertiesOf(object).map(keyName).filter(Boolean) : []
}

/** An export name for a story: a state's path or an example's name, unique and not a reserved word. */
const exportName = (name, taken) => {
  let identifier = name.replace(/[^A-Za-z0-9_$]+(.)?/g, (_, next) => (next ? next.toUpperCase() : ''))
  if (!identifier || /^[0-9]/.test(identifier)) identifier = `_${identifier}`
  if (RESERVED.has(identifier)) identifier = `${identifier}_`
  while (taken.has(identifier)) identifier = `${identifier}_`
  taken.add(identifier)
  return identifier
}

/** A folder's own files: its layer files first, then the rest (helpers, tests), then skins and translations. Not its child components. */
function filesOf(dir) {
  const files = []
  const seen = new Set()
  const add = (file, layer) => {
    if (!file || seen.has(file)) return
    seen.add(file)
    files.push({ file, name: posix(path.relative(dir, file)), layer })
  }
  for (const layer of LAYERS) add(findLayer(dir, layer), layer)
  for (const entry of readdirSync(dir).sort()) {
    const file = path.join(dir, entry)
    if (!isDirectory(file) && CODE.test(entry)) add(file, /\.test\.[cm]?[jt]sx?$/.test(entry) ? 'test' : 'module')
  }
  for (const skin of listSkins(dir)) add(skin.file, 'skin')
  for (const translation of listTranslations(dir)) add(translation.file, 'translation')
  return files
}

const relative = (from, to) => {
  const value = posix(path.relative(path.dirname(from), to))
  return value.startsWith('.') ? value : `./${value}`
}
/** A module to import, as TypeScript wants it: with no `.ts` or `.tsx` at the end. */
const module_ = (from, to) => relative(from, to).replace(/\.tsx?$/, '')

/** One folder's story file. */
function storyFile(options, dir, target) {
  const id = componentPath(options.root, dir)
  const files = filesOf(dir)
  const stateFile = findLayer(dir, 'state')
  const propsFile = findLayer(dir, 'props')
  const states = stateFile ? chartStates(stateFile) : []
  const propExamples = exampleNames(propsFile)
  // A chart's examples are imported only when its file exports them: a missing export is a build warning.
  const chartHasExamples = Boolean(examplesOf(stateFile))
  const reads = readsOf(options.root, dir)
  // The story file's own names, which no story's export may take.
  const taken = new Set(['createElement', 'Pinned', 'Example', 'FolderDocs', 'Component', 'propExamples', 'chartExamples', 'folder', 'sources', 'stateExamples', 'shown', 'pinned'])
  const lines = [
    HEADER,
    `// From ${posix(path.relative(options.cwd, dir))}: its files, what the framework knows of them, and a story per example and per state.`,
    "import { createElement } from 'react'",
    states.length ? "import { Pinned, type Example } from 'framework'" : "import type { Example } from 'framework'",
    `import { FolderDocs } from ${JSON.stringify(module_(target, options.docs))}`,
    `import Component from ${JSON.stringify(relative(target, dir))}`,
    ...(propsFile && propExamples.length ? [`import { examples as propExamples } from ${JSON.stringify(module_(target, propsFile))}`] : []),
    ...(chartHasExamples ? [`import { examples as chartExamples } from ${JSON.stringify(module_(target, stateFile))}`] : []),
    ...files.map((file, index) => `import source${index} from ${JSON.stringify(`${relative(target, file.file)}?raw`)}`),
    '',
    `const folder = ${JSON.stringify({ path: id, reads, states, files: files.map(({ name, layer }) => ({ name, layer })) }, null, 2)}`,
    `const sources = [${files.map((_, index) => `source${index}`).join(', ')}]`,
    ...(states.length
      ? [`const stateExamples: Record<string, Example> = ${chartHasExamples ? 'chartExamples as Record<string, Example>' : '{}'}`]
      : []),
    '',
    'const shown = (example: Example | undefined) => ({',
    '  parameters: { framework: { route: example?.route } },',
    '  render: () => createElement(Component, example?.props as never),',
    '})',
    ...(states.length
      ? [
          'const pinned = (state: string, example: Example | undefined) => ({',
          '  parameters: { framework: { route: example?.route } },',
          `  render: () => createElement(Pinned, { path: ${JSON.stringify(id)}, state, example }, createElement(Component, example?.props as never)),`,
          '})',
        ]
      : []),
    '',
    'export default {',
    `  title: ${JSON.stringify(id)},`,
    '  component: Component,',
    "  tags: ['autodocs'],",
    '  parameters: { framework: { ...folder, sources }, docs: { page: FolderDocs } },',
    '}',
    '',
  ]
  // The component as it runs: with each example of what a parent passes, or with nothing.
  if (propExamples.length) {
    for (const name of propExamples) lines.push(`export const ${exportName(name, taken)} = { name: ${JSON.stringify(name)}, ...shown((propExamples as Record<string, Example>)[${JSON.stringify(name)}]) }`)
  } else {
    // A chart runs from its first state: that state's example says the address and the props it starts with.
    const start = states[0] ? `stateExamples[${JSON.stringify(states[0].path)}]` : 'undefined'
    lines.push(`export const ${exportName('Live', taken)} = { name: 'Live', ...shown(${start}) }`)
  }
  // Each state of its chart, held there.
  for (const state of states) lines.push(`export const ${exportName(state.path, taken)} = { name: ${JSON.stringify(state.path)}, ...pinned(${JSON.stringify(state.path)}, stateExamples[${JSON.stringify(state.path)}]) }`)
  lines.push('')
  return lines.join('\n')
}

/**
 * Writes `<out>/<path>.stories.tsx` for every component folder, and removes those of folders that
 * went. Unchanged files are not rewritten, and each file is renamed into place whole.
 */
export function writeStories(options) {
  const expected = new Map()
  for (const dir of listComponentFolders(options.root)) {
    if (options.skip.includes(componentPath(options.root, dir))) continue
    const target = path.join(options.out, `${componentPath(options.root, dir)}.stories.tsx`)
    expected.set(target, storyFile(options, dir, target))
  }
  const existing = []
  const collect = (dir) => {
    if (!isDirectory(dir)) return
    for (const entry of readdirSync(dir)) {
      const file = path.join(dir, entry)
      if (isDirectory(file)) collect(file)
      else existing.push(file)
    }
  }
  collect(options.out)
  for (const file of existing) if (!expected.has(file)) rmSync(file, { force: true })
  for (const [file, source] of expected) {
    if (existsSync(file) && readFileSync(file, 'utf8') === source) continue
    mkdirSync(path.dirname(file), { recursive: true })
    const temporary = `${file}.${process.pid}.tmp`
    writeFileSync(temporary, source)
    renameSync(temporary, file)
  }
  return expected.size
}

/** A Vite plugin for Storybook's server: the story files follow the folders while it runs. */
export function storiesPlugin(options) {
  return {
    name: 'framework:stories',
    configureServer(server) {
      const inside = (file) => !path.relative(options.root, file).startsWith('..')
      const write = (file) => {
        if (!inside(file) || path.basename(file).startsWith('.')) return
        writeStories(options)
      }
      server.watcher.add(options.root)
      for (const event of ['add', 'unlink', 'addDir', 'unlinkDir']) server.watcher.on(event, write)
      server.watcher.on('change', (file) => {
        if (['state', 'props'].includes(path.basename(file).replace(CODE, ''))) write(file)
      })
    },
  }
}
